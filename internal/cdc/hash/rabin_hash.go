type RabinHash struct {
	windows *list.List
	w       uint64
	p       uint64
	value   uint64
	pow     uint64
}

func NewRabinHash() *RabinHash {
	h := new(RabinHash)
	h.w = 64
	h.p = 257
	h.value = 0
	// h.pow 为 h.p 的 h.w-1 次方再对1的64次方取模的结果
	h.pow = 13725430613427699457
	h.windows = list.New()
	return h
}

func (h *RabinHash) Next(value byte) {
	if h.w == uint64(h.windows.Len()) {
		back := h.windows.Back()
		if back != nil {
			h.value = (h.value-pop[back.Value.(byte)])*h.p + uint64(value)
			h.windows.Remove(h.windows.Back())
			h.windows.PushFront(value)
		}
	} else {
		h.value = h.value*h.p + uint64(value)
		h.windows.PushFront(value)
	}
}

func (h *RabinHash) Reset() {
	h.value = 0
	h.windows.Init()
}

func (h *RabinHash) Check(mask uint64) bool {
	return (h.value & mask) == 0
}
